// One-off generator: converts the datameet India composite GeoJSON into a
// simplified SVG path + projection constants, written to src/lib/india-map.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const geo = JSON.parse(readFileSync(join(tmpdir(), 'india.geojson'), 'utf8'));

// Collect all polygon rings (outer rings only)
const rings = [];
for (const feature of geo.features) {
  const g = feature.geometry;
  if (g.type === 'Polygon') rings.push(g.coordinates[0]);
  else if (g.type === 'MultiPolygon') for (const poly of g.coordinates) rings.push(poly[0]);
}

// Bounds
let lonMin = Infinity, lonMax = -Infinity, latMin = Infinity, latMax = -Infinity;
for (const ring of rings) {
  for (const [lon, lat] of ring) {
    if (lon < lonMin) lonMin = lon;
    if (lon > lonMax) lonMax = lon;
    if (lat < latMin) latMin = lat;
    if (lat > latMax) latMax = lat;
  }
}

// Equirectangular projection, x compressed by cos of mid-latitude
const midLat = ((latMin + latMax) / 2) * (Math.PI / 180);
const cosMid = Math.cos(midLat);
const WIDTH = 600;
const k = WIDTH / ((lonMax - lonMin) * cosMid);
const HEIGHT = (latMax - latMin) * k;

const project = ([lon, lat]) => [(lon - lonMin) * k * cosMid, (latMax - lat) * k];

// Douglas-Peucker simplification in projected space
function simplify(points, tol) {
  if (points.length < 3) return points;
  const sqTol = tol * tol;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay;
    const len2 = dx * dx + dy * dy || 1;
    let maxD = 0, maxI = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      let t = ((px - ax) * dx + (py - ay) * dy) / len2;
      t = Math.max(0, Math.min(1, t));
      const ex = px - (ax + t * dx), ey = py - (ay + t * dy);
      const d = ex * ex + ey * ey;
      if (d > maxD) { maxD = d; maxI = i; }
    }
    if (maxD > sqTol) {
      keep[maxI] = 1;
      stack.push([a, maxI], [maxI, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function ringArea(points) {
  let area = 0;
  for (let i = 0; i < points.length - 1; i++) {
    area += points[i][0] * points[i + 1][1] - points[i + 1][0] * points[i][1];
  }
  return Math.abs(area / 2);
}

const TOL = 0.7;      // px in a 600-wide viewBox
const MIN_AREA = 3;   // drop micro islets

let path = '';
let kept = 0;
for (const ring of rings) {
  const projected = ring.map(project);
  if (ringArea(projected) < MIN_AREA) continue;
  const simple = simplify(projected, TOL);
  if (simple.length < 4) continue;
  kept++;
  path += 'M' + simple.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z';
}

const out = `// Generated by scripts/build-india-path.mjs from datameet/maps india-composite.geojson
// Equirectangular projection; use project() to place lat/long markers on the path.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${Math.ceil(HEIGHT)};

const LON_MIN = ${lonMin};
const LAT_MAX = ${latMax};
const K = ${k};
const COS_MID = ${cosMid};

export function project(lat: number, lon: number): { x: number; y: number } {
  return { x: (lon - LON_MIN) * K * COS_MID, y: (LAT_MAX - lat) * K };
}

export const INDIA_PATH = '${path}';
`;

writeFileSync('src/lib/india-map.ts', out);
console.log(`rings kept: ${kept}, path chars: ${path.length}, viewBox 0 0 ${WIDTH} ${Math.ceil(HEIGHT)}`);
console.log(`bounds: lon ${lonMin.toFixed(2)}..${lonMax.toFixed(2)} lat ${latMin.toFixed(2)}..${latMax.toFixed(2)}`);
